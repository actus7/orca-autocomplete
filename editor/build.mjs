// Builds the plugin's editor: Monaco and our code become plain files in editor/dist, because Orca
// installs a plugin as files and runs it with no network. Run `node editor/build.mjs` after changing
// anything in editor/src or editor/languages.mjs, and commit the result.
//
// Also writes what is derived from the language table: the page of each language, the loader map and
// the `customEditors` of orca-plugin.json.
import { build } from 'esbuild'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { GRAMMARS, PAGES, customEditors, pageFor } from './languages.mjs'

const editorDir = fileURLToPath(new URL('.', import.meta.url))
const pluginDir = `${editorDir}../`
const dev = process.argv.includes('--dev')

function writeIfChanged(path, text) {
  let current = null
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    current = null
  }
  if (current !== text) {
    writeFileSync(path, text)
  }
}

function writePages() {
  mkdirSync(`${editorDir}pages`, { recursive: true })
  const wanted = new Set(PAGES.map((language) => `${language.id}.html`))
  for (const file of readdirSync(`${editorDir}pages`)) {
    if (!wanted.has(file)) {
      rmSync(`${editorDir}pages/${file}`)
    }
  }
  for (const language of PAGES) {
    writeIfChanged(`${editorDir}pages/${language.id}.html`, pageFor(language))
  }
}

function writeLoaders() {
  // Why: Monaco ships no LaTeX grammar, so a language whose rules are not in `basic-languages` keeps
  // its own under editor/grammars/ and the loader points there instead of into the package.
  const local = existsSync(`${editorDir}grammars`)
    ? readdirSync(`${editorDir}grammars`, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
    : []
  const loaderOf = (dir) =>
    local.includes(dir)
      ? `() => import('../grammars/${dir}/${dir}.contribution'),`
      : `() => import('monaco-editor/esm/vs/basic-languages/${dir}/${dir}.contribution'),`
  const dirs = [...new Set(GRAMMARS.map((language) => language.dir))].sort()
  const lines = dirs.map((dir) => `  ${JSON.stringify(dir)}: ${loaderOf(dir)}`)
  const byId = GRAMMARS.map((language) => `  ${JSON.stringify(language.id)}: ${JSON.stringify(language.dir)},`)
  writeIfChanged(
    `${editorDir}src/languages.generated.ts`,
    `// Generated by editor/build.mjs from editor/languages.mjs. Do not edit.
export const grammarLoaders: Record<string, () => Promise<unknown>> = {
${lines.join('\n')}
}

export const grammarOf: Record<string, string> = {
${byId.join('\n')}
}
`
  )
}

function syncManifest() {
  const path = `${pluginDir}orca-plugin.json`
  const manifest = JSON.parse(readFileSync(path, 'utf8'))
  manifest.contributes.customEditors = customEditors()
  writeIfChanged(path, `${JSON.stringify(manifest, null, 2)}\n`)
}

async function bundle() {
  rmSync(`${editorDir}dist`, { recursive: true, force: true })
  const shared = {
    outdir: `${editorDir}dist`,
    bundle: true,
    format: 'esm',
    target: 'es2022',
    loader: { '.ttf': 'dataurl' },
    minify: !dev,
    logLevel: 'warning'
  }
  // Why two builds: the worker is loaded on its own and must not depend on shared chunks.
  await build({ ...shared, entryPoints: { main: `${editorDir}src/main.ts` }, splitting: true, chunkNames: 'chunks/[name]-[hash]' })
  for (const worker of ['editor', 'ts', 'css', 'html']) {
    await build({ ...shared, entryPoints: { [`${worker}.worker`]: `${editorDir}src/${worker}.worker.ts` } })
  }
}

function report(dir, prefix = '') {
  let total = 0
  for (const entry of readdirSync(dir)) {
    const full = `${dir}/${entry}`
    const stat = statSync(full)
    total += stat.isDirectory() ? report(full, `${prefix}${entry}/`) : stat.size
  }
  return total
}

writePages()
writeLoaders()
syncManifest()
await bundle()
const bytes = report(`${editorDir}dist`)
console.log(`editor/dist: ${(bytes / 1024 / 1024).toFixed(2)} MiB, ${GRAMMARS.length} grammars, ${PAGES.length} editors${dev ? ' (dev build)' : ''}`)
